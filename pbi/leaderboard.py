"""Platonic Brain Index leaderboard.

    PBI(model) = mean over datasets d in {EEG, MEG, fMRI} and metrics M in {mutual k-NN, CKA, RSA}
                 of corrected score(model, d, M)          (corrected = raw / sqrt(split-half ceiling),
                                                           averaged over subjects; see pbi/score.py)

Cells a model has no score for (e.g. dataset not processed) are left out of its mean; `n_cells` says how many
of the 9 entered. Reference rows: the brain-brain held-out-subject score (same formula, a subject vs the mean of
the other subjects) and the consensus kernel (mean kernel of all trained vision models). Random-init networks are
ranked like any model and labelled.

Writes LEADERBOARD.md (repo root) and artifacts/results/leaderboard.csv.
"""
from __future__ import annotations

import numpy as np
import pandas as pd

from . import score as sc

CELL_ORDER = [(d, m) for d in sc.DATASETS for m in sc.METRICS]


def _cell(d, m):
    return f"{sc.DS_SHORT[d]}_{m}"


def build(root=None):
    root = sc.art_root(root)
    out = sc.results_dir(root)
    meta = sc.load_models(root)
    S = pd.read_csv(out / "scores.csv")
    R = pd.read_csv(out / "scores_reference.csv")
    R = R[R["included"].astype(bool)]
    Rd = R.groupby(["dataset", "system", "metric"], sort=False)["corrected"].mean().reset_index()
    Rd = Rd.rename(columns={"system": "model"})
    allrows = pd.concat([S[["dataset", "model", "metric", "corrected"]], Rd], ignore_index=True)
    W = allrows.pivot_table(index="model", columns=["dataset", "metric"], values="corrected", aggfunc="first")
    cells = [c for c in CELL_ORDER if c in W.columns]
    W = W[cells]
    W.columns = [_cell(d, m) for d, m in cells]
    pbi = W.mean(axis=1, skipna=True)
    ncell = W.notna().sum(axis=1)
    cip = out / "model_ci.csv"
    CI = pd.read_csv(cip) if cip.exists() else None
    nulp = out / "null_pvalues.csv"
    NP = pd.read_csv(nulp) if nulp.exists() else None
    # EXPLORATORY alternative index (pbi/robustness.py): chance-adjusted mutual k-NN and column-centred RSA
    vp = out / "scores_variants.csv"
    alt = None
    if vp.exists():
        Vv = pd.read_csv(vp)
        Vv["metric"] = Vv["metric"].map({"mknn_chance": "mknn", "rsa_cc": "rsa"})
        A = pd.concat([S[S["metric"] == "cka"][["dataset", "model", "metric", "corrected"]],
                       Vv[["dataset", "model", "metric", "corrected"]]], ignore_index=True)
        A = A.pivot_table(index="model", columns=["dataset", "metric"], values="corrected", aggfunc="first")
        alt = A[[c for c in CELL_ORDER if c in A.columns]].mean(axis=1, skipna=True)
    rows = []
    for m in W.index:
        kind = ("reference" if m in ("brain_heldout", "consensus") else
                "random-init" if sc.is_random(meta, m) else "model")
        r = dict(model=m, kind=kind, PBI=pbi[m], n_cells=int(ncell[m]),
                 PBI_alt=alt.get(m, np.nan) if alt is not None else np.nan)
        if m in meta.index:
            for c in ("family", "modality", "objective", "params", "capability"):
                r[c] = meta.at[m, c]
        elif m == "brain_heldout":
            r.update(family="brain", modality="brain", objective="held-out subjects")
        elif m == "consensus":
            r.update(family="consensus", modality="vision", objective="mean kernel of trained vision models")
        if CI is not None:
            c = CI[(CI["model"] == m) & (CI["metric"] == "PBI")]
            r["PBI_ci_lo"], r["PBI_ci_hi"] = (c["ci_lo"].iloc[0], c["ci_hi"].iloc[0]) if len(c) else (np.nan, np.nan)
        if NP is not None:
            g = NP[NP["model"] == m]
            r["n_cells_above_null"] = int((g["p"] < 0.05).sum()) if len(g) else np.nan
        r.update(W.loc[m].to_dict())
        rows.append(r)
    L = pd.DataFrame(rows).sort_values(["PBI", "model"], ascending=[False, True], kind="stable")
    L = L.reset_index(drop=True)
    L.insert(0, "rank", np.arange(1, len(L) + 1))
    ra = L["PBI_alt"].where(L["kind"] != "reference").rank(ascending=False, method="min")
    L["rank_alt"] = ra.astype("Int64")
    cols = ["rank", "model", "kind", "family", "modality", "objective", "params", "capability", "PBI",
            "PBI_ci_lo", "PBI_ci_hi", "n_cells", "n_cells_above_null", "PBI_alt", "rank_alt"] + list(W.columns)
    L = L[[c for c in cols if c in L.columns]]
    L.to_csv(out / "leaderboard.csv", index=False, float_format="%.4f")
    write_md(L, list(W.columns), root.parent)
    return L


def _f(x, nd=3):
    try:
        return "" if pd.isna(x) else f"{float(x):.{nd}f}"
    except (TypeError, ValueError):
        return str(x)


def _params(x):
    if pd.isna(x):
        return ""
    x = float(x)
    return f"{x / 1e9:.1f}B" if x >= 1e9 else f"{x / 1e6:.0f}M"


def write_md(L, cellcols, repo_dir):
    lines = ["# Platonic Brain Index — leaderboard", "",
             "*Machine-generated by `python -m pbi leaderboard` from committed kernels; do not edit by hand.*", "",
             "**PBI = mean over datasets (THINGS-EEG2, THINGS-MEG, THINGS-fMRI-IT) and metrics (mutual k-NN, "
             "debiased linear CKA, RSA) of the noise-ceiling-corrected alignment** "
             "(corrected = raw / sqrt(split-half ceiling), averaged over subjects). The correction rescales by "
             "reliability but does not remove chance: corrected mutual k-NN sits at about 0.08 (EEG), 0.15 (fMRI) and "
             "0.18 (MEG) for an unrelated model, so cells and datasets are not on a common scale, MEG mutual k-NN "
             "barely separates models, and 1.0 is a heuristic ceiling (see `artifacts/results/robustness.md`). "
             "RSA uses the preregistered correlation-distance RDM, which keeps each feature's mean pattern; this "
             "favours some models (e.g. MAE, random-init networks) in the RSA cells. "
             "**Read the ranking as descriptive, not as a validated brain-likeness ranking.** "
             "`PBI alt` (exploratory, not preregistered) = the same mean with chance-adjusted mutual k-NN "
             "((x-c)/(1-c) on score and ceiling) and column-centred RSA; `alt #` is the rank by it. "
             "`n_cells` = how many of the 9 dataset x metric cells entered the mean; models with fewer cells "
             "are not directly comparable. CI = 95% interval over 80% stimulus subsamples. "
             "`above null` = cells where the score beats the shuffled-stimulus null (p < 0.05, uncorrected).", "",
             "Reference rows: `brain_heldout` = a subject's full kernel scored against the mean of the other "
             "subjects (same correction; not like-for-like with models, which are scored against split halves, so it "
             "overstates the reference; like-for-like values are in `robustness.md`); `consensus` = mean kernel of all trained vision models. Random-init networks "
             "are untrained controls.", ""]
    hdr = ["#", "model", "kind", "family", "modality", "params", "capability", "PBI", "95% CI", "cells",
           "above null", "PBI alt", "alt #"] + cellcols
    lines += ["| " + " | ".join(hdr) + " |", "|" + "---|" * len(hdr)]
    for _, r in L.iterrows():
        name = f"**{r['model']}**" if r["kind"] == "reference" else r["model"]
        vals = [str(r["rank"]), name, r["kind"], str(r.get("family", "")), str(r.get("modality", "")),
                _params(r.get("params")), _f(r.get("capability")), _f(r["PBI"]),
                f"[{_f(r.get('PBI_ci_lo'))}, {_f(r.get('PBI_ci_hi'))}]" if "PBI_ci_lo" in r else "",
                str(r["n_cells"]), "" if pd.isna(r.get("n_cells_above_null", np.nan)) else str(int(r["n_cells_above_null"])),
                _f(r.get("PBI_alt")), "" if pd.isna(r.get("rank_alt")) else str(int(r["rank_alt"]))]
        vals += [_f(r[c]) for c in cellcols]
        lines.append("| " + " | ".join(vals) + " |")
    lines += ["", "Columns `EEG_mknn` ... `fMRI_rsa` are the per-cell corrected scores. "
              "See `artifacts/results/hypotheses.md` for the preregistered tests.", ""]
    (repo_dir / "LEADERBOARD.md").write_text("\n".join(lines))


def main(argv=None):
    import argparse
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--root", default=None)
    a = ap.parse_args(argv)
    build(a.root)


if __name__ == "__main__":
    main()
